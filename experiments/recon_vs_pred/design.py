"""Reconstruction vs contrastive vs prediction: the pre-registered design (see README.md in this folder).

A regime-independent nuisance varies in amplitude and correlation timescale. Fast nuisance has weak start-to-start
correlation but residual dependence across the nearest window edges; slow nuisance persists across the gap.
See the scientific audit amendment in README.md. Other construction parameters remain fixed.

    python experiments/recon_vs_pred/design.py      # writes cpbench/configs/sweep_recon_vs_pred.yaml
"""
import math, os
import numpy as np
from omegaconf import OmegaConf

OMEGA, ALPHA, D, NOISE = 0.12, 0.98, 64, 0.3        # rotation (rad / sample), damping, channels, pixel noise
W, GAP = 64, 32                                     # window and context-target gap (samples), fixed for every learner
TAU = dict(fast=16, slow=2000)                      # nuisance AR(1) timescales (samples); W + GAP = 96
CONDITIONS = dict(N0=("fast", 0.0), F1=("fast", 1.0), F2=("fast", 2.0), S1=("slow", 1.0), S2=("slow", 2.0))
PILOT = ("N0", "F2", "S2")
PILOT_EVAL_SEED, EVAL_SEED = 0, 20261016            # test / val series: the pilot used dataset seed 0; the HPC run uses
                                                    # fresh series (pilot-informed amendment).  Renderings keep seed 0.

LEARNERS = dict(ae="reconstruction", vae="reconstruction", jepa_separate="prediction", jepa_shared="prediction",
                cpc="contrastive (future target)", ts2vec="contrastive (same-time target)")
FAILED_TO_TRAIN = ("cpc",)   # pre-declared before HPC training (label-free check, README): run and reported, never dropped,
                             # but outside the collapse gate; it enters no confirmatory hypothesis
COMMON = dict(window=W, gap=GAP, d=16, batch=256, lr=3e-4, schedule="cosine", min_lr=0.05, stream_version=2)
CONTROLS = dict(untrained=("jepa_shared", dict(steps=0)), raw_flat=("raw_flat", {}), raw_lagcov=("raw_lagcov", {}),
                oracle=("oracle", dict(input="latent", feature="lagcov")))
DETECTORS = [dict(type="hmm", k=16, select="persistence"), dict(type="gmm", k=16, select="persistence")]   # primary: hmm; secondary: gmm (no max over detectors)


def dataset(cond, quick=False, eval_seed=EVAL_SEED):
    speed, sigma_n = CONDITIONS[cond]
    return dict(
        regime=dict(type="markov", K=2, dwell=600),
        sources=[dict(type="composite",
                      sources=[dict(type="oscillator", d=1, quadrature=True, damp=ALPHA, expose="latent",
                                    freq=[OMEGA / (2 * math.pi), -OMEGA / (2 * math.pi)])],
                      transforms=[dict(type="render", D=D, kind="fourier")]),
                 dict(type="composite", scale=sigma_n,
                      sources=[dict(type="ar", d=2, phi=float(np.exp(-1 / TAU[speed])), expose="nuisance")],
                      transforms=[dict(type="render", D=D, kind="fourier")])],
        transforms=[dict(type="fold", blocks=2), dict(type="noise", sigma=NOISE)],
        seed=0, **({} if eval_seed == PILOT_EVAL_SEED else dict(eval_seed=eval_seed)),
        splits=dict(test=[2, 3000], val=[2, 3000]) if quick else dict(test=[8, 16000], val=[4, 8000]))


def write_sweep(path, steps=20000, seeds=(0, 1, 2)):
    cfg = dict(
        name="recon_vs_pred", out="cpbench_runs_recon_vs_pred",
        datasets=[dataset(c) for c in CONDITIONS],
        learners=list(LEARNERS), seeds=list(seeds),
        hparams={"hp.window": [W], "hp.gap": [GAP]},
        overrides=[f"hp.{k}={v}" for k, v in COMMON.items() if k not in ("window", "gap")]
                  + [f"hp.steps={steps}", "hp.warmup=1000", "hp.eval_every=2000", "hp.ckpt_every=2000",
                     "hp.eval_detectors=[gmm,hmm]", "hp.keep_ckpts=[2000,5000,20000]"],
        baselines=["raw_flat", "raw_lagcov"], baseline_hparams={"hp.window": [W]},
        detectors=["hmm", "gmm"], plugins=[],
        slurm=dict(partition="workq", gres="gpu:1", time="12:00:00", signal_lead=900, cpus=32, mem="64G",
                   max_parallel=40, workers=6,
                   setup='export PATH=/lus/lfs1aip2/projects/b5ci/Quique/miniforge3/bin:$PATH; '
                         'python -c "import torch; assert torch.cuda.is_available()" || exit 1',
                   cache="cpbench_cache"))
    OmegaConf.save(OmegaConf.create(cfg), path)
    with open(path) as fh:
        body = fh.read()
    with open(path, "w") as fh:
        fh.write("# Pre-registered reconstruction vs contrastive vs prediction experiment (experiments/recon_vs_pred).\n"
                 "# Generated by experiments/recon_vs_pred/design.py: edit that file, not this one.  Edit slurm.partition\n"
                 "# and slurm.setup for your cluster, then on the cluster:\n"
                 "#   python -m cpbench.hpc.make_sweep cpbench/configs/sweep_recon_vs_pred.yaml && sbatch sweeps/recon_vs_pred/job.sbatch\n"
                 + body)


if __name__ == "__main__":
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    out = os.path.join(root, "cpbench", "configs", "sweep_recon_vs_pred.yaml")
    write_sweep(out); print("written", out)
